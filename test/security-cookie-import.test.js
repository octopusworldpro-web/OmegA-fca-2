"use strict";

const test = require("node:test");
const assert = require("node:assert/strict");
const { parseNetscapeCookies, validateSessionCookies } = require("../src/security/cookies");

test("Netscape import preserves HttpOnly cookies instead of treating them as comments", () => {
  const exported = [
    "# Netscape HTTP Cookie File",
    ".facebook.com\tTRUE\t/\tTRUE\t1893456000\tc_user\t123456789",
    "#HttpOnly_.facebook.com\tTRUE\t/\tTRUE\t1893456000\txs\tsession-token"
  ].join("\n");

  const cookies = parseNetscapeCookies(exported);
  assert.equal(cookies.length, 2);
  assert.equal(cookies[0].key, "c_user");
  assert.equal(cookies[0].hostOnly, false);
  assert.equal(cookies[1].key, "xs");
  assert.equal(cookies[1].httpOnly, true);
  assert.equal(cookies[1].secure, true);
  assert.equal(cookies[1].domain, "facebook.com");
  assert.doesNotThrow(() => validateSessionCookies(cookies));
});

test("Netscape import continues to ignore ordinary comment lines", () => {
  const exported = [
    "# Netscape HTTP Cookie File",
    "# generated by a browser extension",
    "facebook.com\tFALSE\t/\tFALSE\t0\tc_user\t123456",
    "facebook.com\tFALSE\t/\tTRUE\t0\txs\ttoken"
  ].join("\n");

  assert.equal(parseNetscapeCookies(exported).length, 2);
});

test("Netscape import rejects malformed non-comment rows", () => {
  assert.throws(
    () => parseNetscapeCookies("# Netscape HTTP Cookie File\nnot-a-valid-row"),
    /Malformed Netscape cookie row/
  );
});


test("Netscape import rejects malformed expiry fields instead of treating them as session cookies", () => {
  const malformed = [
    "facebook.com\tFALSE\t/\tTRUE\tnot-a-timestamp\tc_user\t123456",
    "facebook.com\tFALSE\t/\tTRUE\t0\txs\ttoken"
  ].join("\n");
  assert.throws(() => parseNetscapeCookies(malformed), /Invalid cookie expiry/);
});


test("EryXen AppState metadata accepts Infinity session expiry and tough-cookie dates", () => {
  const { validateSessionCookies } = require("../src/security/cookies");
  const cookies = validateSessionCookies([
    {
      key: "c_user", value: "123456789", domain: ".facebook.com", path: "/",
      expires: "Infinity", creation: new Date("2026-01-01T00:00:00Z"),
      lastAccessed: new Date("2026-01-02T00:00:00Z"), secure: true, httpOnly: true
    },
    {
      key: "xs", value: "session-token", domain: ".facebook.com", path: "/",
      expires: new Date("2030-01-01T00:00:00Z"), creation: new Date(),
      lastAccessed: new Date(), secure: true, httpOnly: true
    }
  ]);
  assert.equal(cookies[0].expires, undefined);
  assert.equal(cookies[1].expires, Math.floor(Date.parse("2030-01-01T00:00:00Z") / 1000));
  assert.equal(cookies[0].httpOnly, true);
  assert.equal(cookies[1].secure, true);
});

test("browser expirationDate milliseconds are normalized to Unix seconds", () => {
  const { normalizeCookies } = require("../src/security/cookies");
  const cookie = normalizeCookies([{
    key: "sid", value: "session", domain: ".facebook.com",
    expirationDate: 1_893_456_000_000
  }])[0];
  assert.equal(cookie.expires, 1_893_456_000);
});
